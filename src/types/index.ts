export type StudentSituation =
  | 'Activo'
  | 'Inactivo'
  | 'Transferido'
  | 'Desistente'
  | 'Falecido'
  | 'Concluiu'
  | 'Suspenso';

/**
 * MATRÍCULA — registo relacional, um por Ano Lectivo, ligado ao Aluno (Student)
 * por `studentId`. O Aluno tem exactamente UMA ficha de cadastro (identificação,
 * filiação, contactos, documentos — em `Student`), mas pode ter VÁRIAS
 * matrículas ao longo dos anos que estuda na instituição (nova matrícula,
 * renovação, transferência, reingresso). É aqui — e não na ficha do Aluno —
 * que vivem: Ano Lectivo, Classe/Curso/Turma/Turno/Sala, Regime, Tipo e Estado
 * da matrícula, e o Plano Financeiro (matrícula, propina, desconto, forma de
 * pagamento, parcelas). Cada Matrícula, ao ser gravada, gera as obrigações
 * financeiras correspondentes (fatura de Matrícula e 1.ª mensalidade) em
 * `SchoolDatabase.invoices`, e actualiza o "instantâneo" de turma/plano
 * financeiro do Aluno (usado por Turmas, Pautas, Assiduidade, Propinas), sem
 * nunca inventar valores: os montantes vêm sempre da Tabela Financeira real
 * (Configurações → Tabela Financeira) da classe escolhida.
 */
export type MatriculaTipo = 'nova' | 'renovacao' | 'transferencia' | 'reingresso';

export type MatriculaEstado =
  | 'pendente'
  | 'matriculado'
  | 'confirmada'
  | 'cancelada'
  | 'transferida'
  | 'concluida';

export type MatriculaTipoAluno = 'interno' | 'externo' | 'bolseiro' | 'isento';

/**
 * Situação financeira de uma matrícula (substitui o antigo campo "Regime"):
 *  - regular  : parcelas registadas como PAGAS (caixa aberta automaticamente);
 *  - pendente : parcelas registadas como PENDENTES;
 *  - mora     : parcelas já vencidas ficam EM MORA; as ainda por vencer ficam pendentes;
 *  - isento   : isento / bolseiro — sem propinas nesse ano lectivo (só outros serviços).
 */
export type SituacaoFinanceira = 'regular' | 'pendente' | 'mora' | 'isento';

export interface Matricula {
  id: string;
  /** Número de matrícula automático, ex.: MAT-2026/2027-0421. */
  numeroMatricula: string;
  academicYear: string; // "2026/2027"

  // --- Relação com o Aluno (ficha única, em Student) ------------------------
  studentId: string;
  /** Instantâneo apenas para leitura rápida em listagens/recibos — a fonte de
   * verdade destes dados pessoais continua a ser sempre a ficha do Aluno. */
  studentName: string;
  studentProcNumber: string;
  studentAvatar?: string;
  studentGender?: string;
  studentBirthDate?: string;

  // --- Situação anterior à data desta matrícula (para decidir Tipo/Estado) --
  /** Classe que o aluno frequentava antes desta matrícula (classe anterior
   * DENTRO desta instituição, obtida da última Matrícula registada — nunca do
   * Histórico Escolar anterior à instituição, que fica só na ficha do Aluno). */
  previousGrade?: string;
  /** Resultado/situação da matrícula anterior nesta instituição. */
  previousResult?: string;
  /** Matrícula por transferência: escola de onde o aluno veio e nº da Guia de Transferência que trouxe. */
  escolaOrigem?: string;
  guiaTransferenciaNumero?: string;

  // --- 6. Dados da Matrícula (Classe, Curso, Turma) --------------------------
  grade: string; // Classe
  courseName?: string; // Curso/Área Curricular
  classId: string; // Turma (ClassRoom.id)
  className: string;
  shift: string; // Turno
  classroomRoom?: string; // Sala
  regime?: string;
  numeroDeMatricula?: string; // nº de matrícula administrativo/manual, se a secretaria usar numeração própria
  dataMatricula: string; // ISO date
  tipo: MatriculaTipo;
  estado: MatriculaEstado;

  // --- 8. Situação Financeira da Matrícula -----------------------------------
  tipoAluno: MatriculaTipoAluno;
  valorMatriculaKz: number;
  valorPropinaKz: number;
  descontoPercent?: number;
  descontoKz?: number;
  diaVencimento?: number;
  formaPagamento?: string;
  responsavelFinanceiroNome?: string;
  responsavelFinanceiroTelefone?: string;
  numeroParcelas?: number;
  /** Situação financeira ESCOLHIDA ao matricular (define o estado inicial das faturas). A situação REAL
   * (que muda com os pagamentos) calcula-se com `resolveFinancialSituation`. */
  situacaoFinanceira?: SituacaoFinanceira;
  estadoFinanceiro: 'regular' | 'debito' | 'isento';

  // --- Obrigações financeiras geradas a partir desta matrícula ---------------
  /** IDs das faturas (TuitionInvoice) geradas automaticamente ao gravar esta
   * matrícula: a fatura de Matrícula e a 1.ª mensalidade de Propina. */
  generatedInvoiceIds?: string[];

  // --- Auditoria --------------------------------------------------------------
  createdAt: string;
  createdBy?: string;
  updatedAt?: string;
  updatedBy?: string;
  observacoes?: string;
}

