// Professor responsável por lecionar cada uma. A regra aplica-se a TODAS as
// turmas da Classe (e Curso, quando aplicável) — não a uma turma isolada.
//
// Este registo é o que a Pauta Geral (utils/classSubjects.ts) usa, com
// prioridade máxima, para decidir quais colunas de disciplina mostrar numa
// turma. É também distinto de:
//  - Coordenador de Disciplina (`Subject.coordinatorName`): responde pela
//    disciplina a nível institucional, não lecciona necessariamente a turma;
//  - Diretor de Turma (`ClassRoom.headTeacherName`): responsável
//    administrativo pela turma, não pelas disciplinas em si.
