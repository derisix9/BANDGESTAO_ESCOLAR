  /** Hora do dia (HH:mm) em que o backup deve correr. */
  time: string;
  /** Dia da semana (0=Domingo … 6=Sábado), usado quando frequency='semanal'. */
  weekday?: number;
  /** Dia do mês (1-28), usado quando frequency='mensal'. */
  dayOfMonth?: number;
  /** Quantas cópias automáticas mais recentes são mantidas no histórico. */
